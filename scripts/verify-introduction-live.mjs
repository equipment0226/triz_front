// Read-only verification of the deployed public introduction.
import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const base=process.argv[2] || 'https://trizfront-production.up.railway.app';
const browser=await chromium.launch({channel:'msedge',headless:true});
try {
  const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base+'/');
  await page.waitForFunction(()=>{const img=document.querySelector('.hero-research-photo');return img?.complete&&img.naturalWidth>0;});
  assert.ok((await page.locator('.hero-art').innerText()).includes('다양한 산업/직군의 문제점'));
  await page.goto(base+'/?page=tool');
  await page.locator('.chapter-detail').first().waitFor();
  assert.equal(await page.getByRole('button',{name:'Introduction',exact:true}).count(),1);
  assert.ok((await page.locator('.guide-hero').innerText()).includes('문제점을 설명하고'));
  await page.waitForFunction(()=>{const img=document.querySelector('.human-ai-image img');return img?.complete && img.naturalWidth>0;});
  assert.equal(await page.locator('.guide-hero svg.guide-visual').count(),0);
  assert.ok((await page.locator('.human-label').innerText()).includes('질문, 검토'));
  assert.ok((await page.locator('.ai-label').innerText()).includes('구조화, 분석, 아이디어 도출'));
  assert.equal(await page.locator('.chapter-detail').count(),4);
  assert.equal(await page.getByRole('tab',{name:'Tool 소개',exact:true}).getAttribute('aria-selected'),'true');
  await page.getByRole('tab',{name:'TRIZ란?',exact:true}).click();
  await page.locator('.triz-prose').waitFor();
  await page.waitForFunction(()=>{const img=document.querySelector('.triz-founder img');return img?.complete && img.naturalWidth>0;});
  await page.screenshot({path:'test-results/live-triz.png',fullPage:true});
  await page.goto(base+'/?page=tool&material=standards');
  await page.locator('.standard-class-toggle').first().waitFor();
  assert.equal(await page.locator('.standard-class-toggle').count(),5);
  assert.equal(await page.locator('.library-entry').count(),0);
  await page.getByLabel('자료 검색').fill('2.4.12');
  await page.locator('.standard-leaf').click();
  assert.ok((await page.locator('.standard-reading').innerText()).includes('전기유변'));
  await page.waitForFunction(()=>{const img=document.querySelector('.standard-specific-diagram img');return img?.complete&&img.naturalWidth>0;});
  assert.equal(await page.locator('.standard-specific-diagram img').getAttribute('src'),'/diagrams/standards/2.4.12.svg');
  const standardCodes=['1.2.3','2.4.12','4.5.2','5.4.2','5.5.3'];
  for(const code of standardCodes) {
    const response=await page.request.get(base+`/diagrams/standards/${code}.svg`);
    assert.equal(response.status(),200);
    assert.ok((await response.text()).includes(`data-standard-code="${code}"`));
  }
  await page.goto(base+'/?page=tool&material=separation');
  for(const entry of await page.locator('.library-entry').all()) {
    await entry.locator('summary').click();
    assert.equal(await entry.locator('[data-active=true]').count(),1);
    assert.equal(await entry.locator('[data-active=false] rect[fill="#fff"]').count(),3);
  }
  await page.goto(base+'/?page=tool&material=ariz');
  await page.locator('.library-entry summary').first().waitFor();
  for(const summary of await page.locator('.library-entry summary').all()) await summary.click();
  assert.equal(await page.locator('.ariz-part-diagram').count(),9);
  assert.equal(await page.locator('.ariz-diagram-steps li').count(),41);
  await page.goto(base+'/?page=tool&material=business');
  await page.getByRole('img',{name:'서류가방과 문서로 표현한 비즈니스 문제 분석'}).waitFor();
  assert.equal(await page.locator('.business-hero-photo').count(),0);
  await page.goto(base+'/?page=tool&material=matrix');
  await page.locator('.principle-links a').filter({hasText:'#15 '}).click();
  await page.waitForFunction(()=>document.querySelector('#material-principles-15')?.open);
  assert.ok(await page.locator('#material-principles-15').evaluate(el=>el.getBoundingClientRect().top<180));
  await page.goto(base+'/?page=tool&chapter=04');
  await page.locator('.technique-card').first().waitFor();
  assert.equal(await page.locator('.guide-next').count(),0);
  await page.goto(base+'/?page=tool&chapter=03');
  await page.locator('.technique-card').first().waitFor();
  assert.equal(await page.locator('.technique-card table').count(),await page.locator('.technique-card').count());
  assert.equal(await page.locator('.template-download,.template-source').count(),0);
  assert.ok((await page.locator('#technique-technical').innerText()).includes('특성 B · 강도'));
  assert.ok((await page.locator('#technique-physical').innerText()).includes('동일한 특성 · 벽의 두께'));
  await page.goto(base+'/?page=tool&material=effects');
  await page.locator('.effect-function-toggle').first().waitFor();
  const total=await page.locator('.library-total').innerText();
  assert.equal(await page.locator('.library-entry').count(),0);
  assert.equal(await page.locator('.effect-leaf').count(),0);
  assert.equal(await page.locator('.effect-function-toggle').count(),19);
  await page.getByLabel('자료 검색').fill('열전');
  assert.ok(await page.locator('.effect-leaf').count()>0);
  await page.locator('.effect-leaf').first().click();
  await page.screenshot({path:'test-results/live-effects.png',fullPage:true});
  await page.getByLabel('자료 검색').fill('ESC');
  assert.equal(await page.locator('.effect-leaf').count(),1);
  await page.locator('.effect-leaf').click();
  assert.deepEqual(await page.locator('.effect-reading th').allTextContents(),['자료 식별자','요구 기능','작동 원리','필요 조건']);
  await page.reload();
  await page.locator('.effect-reading h2').waitFor();
  assert.ok((await page.locator('.effect-reading h2').innerText()).includes('ESC'));
  await page.setViewportSize({width:390,height:844});
  await page.locator('.effect-reading .standard-mobile-back').click();
  await page.locator('.effect-leaf.selected').click();
  assert.ok(await page.locator('.effects-tree').isHidden());
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  await page.screenshot({path:'test-results/live-effects-mobile.png',fullPage:true});
  await page.goto(base+'/?page=tool');
  await page.locator('.chapter-detail').first().waitFor();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({url:base+'/?page=tool',status:'VERIFIED',standards:76,effects:total,checks:['default tab','TRIZ portrait','four chapters','templates','standards','effect explorer and deep link','mobile']}));
} finally {await browser.close();}
